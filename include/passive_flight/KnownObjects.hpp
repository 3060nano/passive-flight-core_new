#pragma once

#include "passive_flight/ObjectModel.hpp"

namespace passive_flight {
    /**
     * Создаёт контрольную числовую модель авиабомбы ФАБ-1500Т
     * с готовыми массовыми и аэродинамическими характеристиками.
     *
     * Источник:
     * А.Г. Постников, В.С. Чуйко,
     * "Методы решения прикладных задач внешней баллистики",
     * 1979, таблица 1.1.
     *
     * Модель служит контрольным объектом для валидации последовательности
     * «табличная аэродинамика — динамика — траектория» и регистрируется
     * в стандартном ObjectRegistry под стабильным идентификатором.
     *
     * @return Полностью заполненная числовая модель в единицах СИ.
     */
    [[nodiscard]]
    ObjectModel makeFab1500TPostnikovModel();

    /**
     * Возвращает табличные аэродинамические характеристики
     * ФАБ-1500Т из того же источника.
     *
     * @return Пять таблиц коэффициентов и производных в функции числа Маха.
     */
    [[nodiscard]]
    TabulatedAerodynamicData
    makeFab1500TPostnikovAerodynamicData();

    /**
     * Создаёт расчётную модификацию модели ФАБ-1500Т.
     *
     * Производные `Cy^alpha(M)`, `mz^alpha(M)` и `mz^(omegaBar)(M)`
     * интерполированы из отдельного пользовательского набора данных,
     * а `Cx0(M)` увеличен на 5 % относительно модели Постникова—Чуйко.
     * Библиографическое описание пользовательского набора в репозитории
     * отсутствует, поэтому модель не следует интерпретировать как данные
     * первичного источника.
     *
     * @return Числовая модель в единицах СИ с табличной аэродинамикой.
     */
    [[nodiscard]]
    ObjectModel makeFab1500TModifiedModel();

    /**
     * Возвращает аэродинамические таблицы расчётной модификации ФАБ-1500Т.
     *
     * Аргумент таблиц — безразмерное число Маха. Коэффициенты `Cx0`, `Cy0`
     * и `mz0` безразмерны; производные по углу атаки выражены в рад⁻¹,
     * коэффициент при `alpha²` — в рад⁻².
     *
     * @return Набор интерполированных и производных табличных зависимостей.
     */
    [[nodiscard]]
    TabulatedAerodynamicData
    makeFab1500TModifiedAerodynamicData();

    /**
     * Создаёт расчётную планирующую модификацию ФАБ-1500Т.
     *
     * Характерная площадь соответствует площади крыла с подфюзеляжной
     * частью. Постоянная составляющая `mz0(M)` обеспечивает нулевой
     * статический момент при угле атаки 1,5° и нулевой угловой скорости.
     *
     * @return Числовая модель планирующей модификации в единицах СИ.
     */
    [[nodiscard]]
    ObjectModel makeFab1500TGlideModel();

    /**
     * Возвращает аэродинамические таблицы планирующей модификации.
     *
     * Постоянные составляющие вычислены при
     * `alpha_trim = 1,5° = pi/120 рад` по формулам
     * `Cy0 = Cy^alpha*alpha_trim` и
     * `mz0 = -mz^alpha*alpha_trim`.
     *
     * @return Расчётный набор табличных аэродинамических характеристик.
     */
    [[nodiscard]]
    TabulatedAerodynamicData
    makeFab1500TGlideAerodynamicData();
} // namespace passive_flight

