#pragma once

#include <cstddef>
#include <string>
#include <vector>

namespace passive_flight {

/*
 * СИСТЕМА КООРДИНАТ И ЗНАКОВ
 *
 * x:
 *   Горизонтальная координата.
 *   Положительное направление совпадает с направлением движения
 *   носителя в момент сброса.
 *
 * H:
 *   Геометрическая высота.
 *   Положительное направление — вверх.
 *
 * Theta:
 *   Угол наклона траектории к местному горизонту.
 *   Положительный угол соответствует набору высоты.
 *   Отрицательный угол соответствует снижению.
 *
 * theta:
 *   Угол тангажа продольной оси объекта.
 *   Положительный угол соответствует поднятию носа.
 *
 * omegaZ:
 *   Угловая скорость тангажа.
 *   Положительна при увеличении theta.
 *
 * alpha:
 *   Угол атаки:
 *
 *       alpha = theta - Theta.
 *
 * Все размерные значения передаются в единицах СИ.
 * Все углы внутри ядра задаются в радианах.
 */

/// Параметры начального горизонтального сброса пассивного объекта.
/// Углы траектории и тангажа, а также угловая скорость в этом режиме равны нулю.
struct ReleaseConditions {
    /// Геометрическая высота точки сброса над принятой поверхностью, м.
    double altitudeM{};

    /// Модуль воздушной скорости объекта в момент сброса, м/с.
    double speedMps{};
};

/// Запрос на расчёт невозмущённой траектории выбранного объекта.
struct SimulationRequest {
    /// Стабильный строковый идентификатор объекта в ObjectRegistry, безразмерная строка.
    std::string objectId;

    /// Начальные условия горизонтального сброса в единицах СИ.
    ReleaseConditions release;
};

/// Вектор состояния невозмущённого продольного движения
/// `[V, Theta, omega_z, theta, x, H]` и соответствующий момент времени.
/// Время хранится вместе с состоянием, но не входит в число неизвестных системы.
struct State {
    /// Время от момента сброса, с.
    double timeS{};

    /// Модуль воздушной скорости `V`, м/с.
    double speedMps{};

    /// Угол наклона траектории `Theta` к местному горизонту, рад.
    double flightPathAngleRad{};

    /// Угловая скорость тангажа `omega_z = d(theta)/dt`, рад/с.
    double pitchRateRadps{};

    /// Угол тангажа продольной оси `theta`, рад.
    double pitchAngleRad{};

    /// Горизонтальная координата `x` от точки сброса, м.
    double downrangeM{};

    /// Геометрическая высота `H` над принятой поверхностью, м.
    double altitudeM{};

    /// Вычисляет угол атаки по кинематическому соотношению
    /// `alpha = theta - Theta`.
    /// @return Угол атаки `alpha`, рад.
    [[nodiscard]] double angleOfAttackRad() const noexcept {
        return pitchAngleRad - flightPathAngleRad;
    }
};

/// Правая часть системы дифференциальных уравнений невозмущённого движения.
struct StateDerivative {
    /// Производная скорости `dV/dt`, м/с².
    double speedMps2{};

    /// Производная угла наклона траектории `dTheta/dt`, рад/с.
    double flightPathAngleRadps{};

    /// Угловое ускорение тангажа `d(omega_z)/dt`, рад/с².
    double pitchRateRadps2{};

    /// Производная угла тангажа `d(theta)/dt = omega_z`, рад/с.
    double pitchAngleRadps{};

    /// Горизонтальная составляющая скорости `dx/dt`, м/с.
    double downrangeMps{};

    /// Вертикальная составляющая скорости `dH/dt`, м/с.
    double altitudeMps{};
};

/// Сокращённый набор параметров атмосферы, используемый в общих типах расчёта.
struct Environment {
    /// Плотность воздуха `rho`, кг/м³.
    double densityKgM3{};

    /// Локальная скорость звука `a`, м/с.
    double speedOfSoundMps{};

    /// Динамическая вязкость воздуха `mu`, Па·с.
    double dynamicViscosityPaS{};
};

/// Безразмерные аэродинамические коэффициенты продольных сил.
struct ForceCoefficients {
    /// Коэффициент лобового сопротивления `Cx`, безразмерный.
    double drag{};

    /// Коэффициент подъёмной (нормальной) силы `Cy`, безразмерный.
    double lift{};
};

/// Диагностические величины, вычисленные по состоянию на одном шаге траектории.
/// Они не являются независимыми компонентами вектора состояния.
struct StepDiagnostics {
    /// Угол атаки `alpha = theta - Theta`, рад.
    double angleOfAttackRad{};

    /// Производная угла атаки `d(alpha)/dt`, рад/с.
    double angleOfAttackRateRadps{};

    /// Число Маха `M = V/a`, безразмерное.
    double mach{};

    /// Число Рейнольдса `Re = rho*V*D/mu`, безразмерное.
    double reynolds{};

    /// Скоростной напор `q = rho*V²/2`, Па.
    double dynamicPressurePa{};

    /// Коэффициент лобового сопротивления `Cx`, безразмерный.
    double dragCoefficient{};

    /// Коэффициент нормальной силы `Cy`, безразмерный.
    double liftCoefficient{};

    /// Коэффициент продольного момента `mz`, безразмерный.
    double pitchingMomentCoefficient{};

    /// Модуль силы лобового сопротивления `X = q*S*Cx`, Н.
    double dragN{};

    /// Нормальная аэродинамическая сила `Y = q*S*Cy`, Н.
    double liftN{};

    /// Продольный момент `Mz = q*S*L_ref*mz`, Н·м.
    double pitchingMomentNm{};
};

/// Одна точка истории движения для анализа и построения графиков.
struct TrajectorySample {
    /// Состояние объекта в соответствующий момент времени, в единицах СИ.
    State state;

    /// Производные диагностические величины для этого состояния.
    StepDiagnostics diagnostics;
};

/// Причина прекращения численного интегрирования траектории.
enum class TerminationReason {
    /// Объект достиг заданной высоты поверхности.
    GroundReached,

    /// Достигнута предельная длительность расчёта.
    MaximumTimeReached,

    /// Выполнено предельно допустимое число шагов интегрирования.
    MaximumStepsReached,

    /// Входные параметры не удовлетворяют контракту модели.
    InvalidInput,

    /// В процессе интегрирования получено недопустимое состояние.
    InvalidState
};

/// Настройки численного интегрирования и сохранения истории траектории.
struct SimulationOptions {
    /// Номинальный шаг явного метода Эйлера, с.
    double timeStepS{0.001};

    /// Предельное время моделирования от момента сброса, с.
    double maximumTimeS{300.0};

    /// Предельное число шагов интегрирования, безразмерный счётчик.
    std::size_t maximumSteps{2'000'000};

    /// Геометрическая высота поверхности, при достижении которой фиксируется падение, м.
    double groundAltitudeM{0.0};

    /// Признак сохранения дискретной истории состояний.
    bool saveHistory{true};

    /// Число шагов интегрирования между соседними сохраняемыми точками.
    std::size_t historyStride{1};
};

/// Полный результат невозмущённого моделирования с необязательной историей.
struct SimulationResult {
    /// Причина завершения численного интегрирования.
    TerminationReason terminationReason{
        TerminationReason::InvalidState
    };

    /// Последнее корректное состояние либо интерполированное состояние встречи с землёй.
    State finalState{};

    /// Сохранённые точки траектории в хронологическом порядке.
    std::vector<TrajectorySample> history;
};

/// Краткие параметры падения, передаваемые во внешние интерфейсы и SimInTech.
struct SimulationSummary {
    /// Горизонтальная дальность от точки сброса до конечного состояния, м.
    double downrangeM{};

    /// Время от сброса до конечного состояния, с.
    double fallTimeS{};

    /// Модуль скорости в конечном состоянии, м/с.
    double impactSpeedMps{};

    /// Угол наклона траектории в конечном состоянии, рад.
    double impactFlightPathAngleRad{};

    /// Угол тангажа в конечном состоянии, рад.
    double impactPitchAngleRad{};

    /// Угол атаки `theta - Theta` в конечном состоянии, рад.
    double impactAngleOfAttackRad{};

    /// Причина завершения расчёта, определяющая физический смысл конечного состояния.
    TerminationReason terminationReason{
        TerminationReason::InvalidState
    };
};

} // namespace passive_flight
