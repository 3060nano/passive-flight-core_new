#pragma once

#include <algorithm>
#include <vector>

namespace passive_flight {

/**
 * Естественный кубический сплайн.
 *
 * Используется для интерполяции аэродинамических
 * коэффициентов по числу Маха (аналог блока
 * «Кубическая сплайн-интерполяция» в SimInTech).
 *
 * Граничные условия: вторая производная на концах равна нулю.
 */
class CubicSpline {
public:
    /// Создаёт пустой сплайн, не содержащий интерполяционных узлов.
    CubicSpline() = default;

    /// Строит естественный кубический сплайн по табличным узлам.
    /// На каждом интервале используется полином
    /// `S_i(dx) = a_i + b_i*dx + c_i*dx² + d_i*dx³`, а на концах
    /// выполняются условия `S''(x_0) = S''(x_n) = 0`.
    /// @param x Строго возрастающие абсциссы; единицы задаются вызывающим кодом.
    /// @param y Ординаты в согласованных единицах; число значений равно числу x.
    /// @throws std::invalid_argument Если узлов меньше двух, размеры различаются
    /// или абсциссы не возрастают строго.
    void build(
        const std::vector<double>& x,
        const std::vector<double>& y
    );

    /// Вычисляет значение построенного сплайна в заданной абсциссе.
    /// За пределами таблицы возвращает ближайшее граничное значение, то есть
    /// применяет постоянное продолжение без полиномиальной экстраполяции.
    /// @param x Абсцисса в тех же единицах, в которых сплайн был построен.
    /// @return Интерполированная ордината в единицах исходного массива y.
    /// @throws std::logic_error Если метод build ещё не вызывался.
    [[nodiscard]]
    double evaluate(double x) const;

    /// Проверяет наличие построенной интерполяционной зависимости.
    /// @return `true`, если таблица узлов пуста; иначе `false`.
    [[nodiscard]]
    bool empty() const noexcept {
        return x_.empty();
    }

private:
    /// Абсциссы интерполяционных узлов в единицах аргумента.
    std::vector<double> x_;

    /// Исходные ординаты узлов в единицах интерполируемой величины.
    std::vector<double> y_;

    /// Коэффициенты `a_i` локальных кубических полиномов, в единицах y.
    std::vector<double> a_;

    /// Коэффициенты `b_i`, имеющие размерность `y/x`.
    std::vector<double> b_;

    /// Коэффициенты `c_i`, имеющие размерность `y/x²`.
    std::vector<double> c_;

    /// Коэффициенты `d_i`, имеющие размерность `y/x³`.
    std::vector<double> d_;
};

} // namespace passive_flight
