    ObjectModel makeFab1500TPostnikovModel() {
        ObjectModel object;

        object.id = "FAB_1500T_POSTNIKOV_1979";

        object.metadata.displayName = "ФАБ-1500Т — контрольная табличная модель";

        object.metadata.modelVersion = "1.0.0";

        object.metadata.description =
                "Контрольная модель свободнопадающей авиабомбы "
                "ФАБ-1500Т с готовыми массовыми и "
                "аэродинамическими характеристиками по "
                "Постникову и Чуйко, 1979.";

        /*
         * Масса, поперечный момент инерции и продольная координата
         * центра масс заданы соответственно в кг, кг·м² и метрах.
         */
        object.mass.massKg = 1519.0;

        object.mass.pitchMomentOfInertiaKgM2 = 1122.3;

        object.mass.centerOfMassXM = 1.16;

        /*
         * Полная длина и максимальный диаметр корпуса заданы в метрах.
         */
        object.body.lengthM = 3.46;

        object.body.diameterM = 0.58;

        /*
         * В качестве характерной площади принята площадь миделя корпуса:
         *
         *     Sref = pi * D^2 / 4,
         *
         * где D — максимальный диаметр корпуса, м; Sref измеряется в м².
         */
        object.reference.areaM2 =
                std::numbers::pi_v<double> *
                object.body.diameterM *
                object.body.diameterM /
                4.0;

        /*
         * Характерная длина Lref, используемая при нормировке коэффициента
         * продольного момента, равна полной длине корпуса бомбы.
         */
        object.reference.referenceLengthM = object.body.lengthM;

        object.aerodynamicModelType = AerodynamicModelType::Tabulated;

        object.tabulatedAerodynamics = makeFab1500TPostnikovAerodynamicData();

        return object;
    }

